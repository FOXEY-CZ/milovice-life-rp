import assert from 'node:assert/strict';
import {createProceduralCarOwnership} from './procedural-car-ownership.js';
const resource=()=>({calls:0,dispose(){this.calls++;}});
const mesh=(geometry,material,instance=false)=>({isMesh:true,geometry,material,isInstancedMesh:instance,calls:0,dispose(){this.calls++;}});
const group=nodes=>({isGroup:true,parent:null,nodes,traverse(fn){for(const node of this.nodes)fn(node);}});
const manager=createProceduralCarOwnership();
const material=resource(),shared=resource(),unused=resource(),merged=resource(),archGeometry=resource();
const srcArch=mesh(archGeometry,material,true),cloneArch=mesh(archGeometry,material,true);
const original={group:group([mesh(shared,material),mesh(unused,material),srcArch])};
const selected={group:group([mesh(shared,material),mesh(merged,material),cloneArch])};
const lease=manager.register(original,selected);
assert.equal(lease.geometryCount,4);assert.equal(lease.instanceCount,2);
assert.throws(()=>manager.register(original,selected),/once/);
assert.throws(()=>manager.register({group:group([mesh(shared,material)])}),/already owned/);
const otherGeo=resource(),other={group:group([mesh(otherGeo,material)])};
const otherLease=manager.register(other);
selected.group.parent={};
assert.throws(()=>lease.release(),/Detach/);
assert.equal(shared.calls,0);selected.group.parent=null;
// Later GLB attachment uses a different owner. Do not traverse or dispose it.
const glbGeo=resource(),glbMat=resource();selected.group.nodes.push(mesh(glbGeo,glbMat));
assert.equal(lease.release(),true);assert.equal(lease.release(),false);assert.equal(lease.released,true);assert.throws(()=>manager.register(original,selected),/once/);
for(const r of [shared,unused,merged,archGeometry,srcArch,cloneArch])assert.equal(r.calls,1);
for(const r of [glbGeo,glbMat,otherGeo,material])assert.equal(r.calls,0);
assert.equal(otherLease.release(),true);assert.equal(otherGeo.calls,1);assert.equal(material.calls,0);
const fallbackGeo=resource(),fallback={group:group([mesh(fallbackGeo,material)])};
const fallbackLease=manager.register(fallback);
assert.equal(fallbackLease.geometryCount,1);assert.equal(fallbackLease.release(),true);assert.equal(fallbackGeo.calls,1);
console.log('PASS procedural geometry ownership: clone, fallback, alias guard, shared materials, external attachment and idempotent disposal');
