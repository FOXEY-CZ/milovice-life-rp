import assert from 'node:assert/strict';
import {createPerformanceGovernor,GRAPHICS_TIER} from './performance-governor.js';
const phone=createPerformanceGovernor({mobile:true,baselineDpr:1.6});
assert.equal(phone.profile().tier,0);
assert.equal(phone.profile().view,440);
assert.equal(phone.profile().dpr,1.6);
assert.equal(phone.observe(27).changed,false);
let r=phone.observe(27);assert.equal(r.changed,true);assert.equal(r.tier,1);
assert.equal(r.dpr,1.6,'low FPS must NEVER blur the canvas');
assert.equal(r.view,415);
phone.observe(27);r=phone.observe(27);assert.equal(r.tier,2);
phone.observe(27);r=phone.observe(27);assert.equal(r.tier,3);
assert.equal(r.dpr,1.6);
assert.equal(r.detail,120);
assert.equal(phone.observe(43).changed,false);
for(let i=0;i<5;i++)assert.equal(phone.observe(57).changed,false);
r=phone.observe(57);assert.equal(r.changed,true);assert.equal(r.tier,2);
assert.equal(r.dpr,1.6);
const hi=phone.setMode('realistic');assert.equal(hi.dpr,2);
for(let i=0;i<20;i++)assert.equal(phone.observe(18).tier,2);
const balanced=phone.setMode('balanced');assert.equal(balanced.dpr,1.6);
const desktop=createPerformanceGovernor({mobile:false,baselineDpr:1.25});
for(let i=0;i<20;i++)desktop.observe(19);
assert.equal(desktop.profile().tier,0);
assert.equal(desktop.profile().dpr,1.25);
assert(GRAPHICS_TIER.every(x=>x.view>=x.detail));
console.log('Performance governor OK: adaptive distance-only LOD and fixed sharp DPR across FPS tiers');
