import assert from 'node:assert/strict';
import {createGpsCue5330} from './gps-cue-5330.js';
import {nextRouteInstruction5327 as next} from './map-route-instructions-5327.js';
const p=(x,y)=>({x,y}),leg=(a,b,id)=>({a,b,osmId:id});
const build=(legs,offset=0)=>({status:'ready',legs,distanceMetres:legs.reduce((n,l)=>n+Math.hypot(l.b.x-l.a.x,l.b.y-l.a.y),0),startOffset:offset});
const audit=r=>({valid:true,legCount:r.legs.length});
const run=(r,player)=>next(r,audit(r),player);
const right=build([leg(p(0,0),p(100,0),1),leg(p(100,0),p(100,50),2)]);
assert.deepEqual(run(right,p(20,0)),{direction:'right',maneuverKey:'turn:1:2:10000,0',distanceMetres:80,angleDegrees:90,geometricOnly:true,junctionVerified:false,entranceVerified:false});
assert.equal(run(right,p(40,0)).distanceMetres,60);
assert.equal(run(right,p(20,13)),null);
const left=build([leg(p(0,0),p(100,0),1),leg(p(100,0),p(100,-50),2)]);
assert.equal(run(left,p(20,0)).direction,'left');
const reverse=build([leg(p(0,0),p(100,0),1),leg(p(100,0),p(50,0),2)]);
assert.equal(run(reverse,p(0,0)).direction,'reverse');
const curve=build([leg(p(0,0),p(100,0),1),leg(p(100,0),p(100,50),1)]);
assert.equal(run(curve,p(20,0)).direction,'road-end');
assert.equal(run(curve,p(20,0)).distanceMetres,130);
const gap=build([leg(p(0,0),p(100,0),1),leg(p(101,0),p(101,50),2)]);
assert.equal(run(gap,p(20,0)),null);
const ambiguous=build([leg(p(0,0),p(20,0),1),leg(p(20,0),p(20,1),2),leg(p(20,1),p(0,1),3)]);
assert.equal(run(ambiguous,p(2,.5)),null);
assert.equal(next(right,{valid:false,legCount:2},p(0,0)),null);
assert.equal(next(right,{valid:true,legCount:1},p(0,0)),null);
assert.equal(run({...right,status:'off-road'},p(0,0)),null);
assert.equal(run({...right,distanceMetres:999},p(0,0)),null);
assert.equal(run(right,p(NaN,0)),null);
// Composition regression: successive right turns on rebuilt, clipped routes.
const bend1=build([leg(p(20,0),p(100,0),1),leg(p(100,0),p(100,50),2),leg(p(100,50),p(50,50),3)]);
const clipped=build([leg(p(80,0),p(100,0),1),leg(p(100,0),p(100,50),2),leg(p(100,50),p(50,50),3)]);
const bend2=build([leg(p(100,5),p(100,50),2),leg(p(100,50),p(50,50),3)]);
const i1=run(bend1,p(20,0)),i2=run(clipped,p(80,0)),i3=run(bend2,p(100,5));
assert.equal(i1.maneuverKey,i2.maneuverKey);
assert.notEqual(i1.maneuverKey,i3.maneuverKey);
assert.equal(i3.direction,'right');assert.equal(i3.distanceMetres,45);
const composed=createGpsCue5330(),goal={};
const step=(now,instruction)=>composed.update({enabled:true,mapOpen:false,walking:false,target:goal,instruction,now});
assert.equal(step(0,i1),'right');assert.equal(step(8000,i2),'right');
assert.equal(step(9000,i3),null);assert.equal(step(16000,i3),'right');
assert.equal(step(24000,i3),null);
console.log('PASS 5.327 geometric route turns, progress, ambiguity and safe fallback');
