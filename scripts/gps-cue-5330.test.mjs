import assert from 'node:assert/strict';
import {createGpsCue5330 as create,gpsTonePatterns5330 as patterns} from './gps-cue-5330.js';
const cue=create(),target={},other={};
const at=(now,d,extra={})=>cue.update({enabled:true,mapOpen:false,walking:false,target,instruction:{direction:'right',distanceMetres:d},now,...extra});
assert.equal(at(0,81),null);
assert.equal(at(1,80),'right');
assert.equal(at(2,20),null);
assert.equal(at(8001,20),'right');
assert.equal(at(16001,19),null);
assert.equal(at(17000,141),null);
assert.equal(at(17001,70),'right');
assert.equal(at(26000,10,{mapOpen:true}),null);
assert.equal(at(26001,10,{walking:true}),null);
assert.equal(at(26002,10,{enabled:false}),null);
assert.equal(at(26003,10),'right');
assert.equal(at(35000,50,{target:other}),'right');
assert.equal(at(44000,50,{target:other,instruction:{direction:'left',distanceMetres:50}}),'left');
assert.equal(at(53000,NaN),null);
assert.equal(at(53001,10,{instruction:{direction:'fake',distanceMetres:10}}),null);
cue.reset();assert.equal(at(53002,10),'right');
assert.equal(at(54000,10,{target:other}),null);
assert.ok(Object.values(patterns).every(p=>p.length<=3&&p.every(f=>Number.isFinite(f)&&f>0)));
// A distinct turn in the same direction must not inherit the previous distance stage.
const keyed=create(),keyTarget={};
const keyAt=(now,d,key)=>keyed.update({enabled:true,mapOpen:false,walking:false,target:keyTarget,instruction:{direction:'right',distanceMetres:d,maneuverKey:key},now});
assert.equal(keyAt(0,60,'A'),'right');
assert.equal(keyAt(8000,15,'A'),'right');
assert.equal(keyAt(9000,45,'B'),null);
assert.equal(keyAt(16000,40,'B'),'right');
assert.equal(keyAt(24000,39,'B'),null);
assert.equal(keyAt(24001,15,'B'),'right');
