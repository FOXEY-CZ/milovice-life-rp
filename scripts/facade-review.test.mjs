import assert from 'node:assert/strict';
import {planFacadeViews,nextStreetHouse} from './facade-review.js';
const point=(north,east)=>[50.228+north/111320,14.884+east/(111320*Math.cos(50.228*Math.PI/180))];
const coords=[point(-5,-6),point(-5,6),point(5,6),point(5,-6)];
const road=[{name:'Mírová',coords:[point(-14,-25),point(-14,25)]}];
const building={coords,street:'Mírová',id:101};
const faces=planFacadeViews(building,road);
assert.equal(faces.length,4);
assert.deepEqual(new Set(faces.map(x=>x.id)),new Set(['N','S','E','W']));
assert.equal(faces[0].id,'S','road-facing facade should appear first');
assert(faces[0].roadDistance>5&&faces[0].roadDistance<12);
assert(Math.abs(faces[0].yaw)<.08,'bearing to south facade from south road should face north');
assert(faces.every(x=>x.lengthMeters>8));
assert.equal(planFacadeViews(building,[]).filter(x=>x.viewpoint).length,0,'never invent panoramas');
assert.equal(planFacadeViews({coords:[]},road).length,0);
const houses=[{id:101,street:'Mírová'},{id:102,street:'Mírová'},{id:103,street:'Mírová'}];
assert.equal(nextStreetHouse(houses,{},101,'Mírová').id,102);
assert.equal(nextStreetHouse(houses,{'102':{stage:'verified'}},101,'Mírová').id,103);
assert.equal(nextStreetHouse(houses,{'103':{stage:'verified'}},103,'Mírová').id,101);
assert.equal(nextStreetHouse(houses,{},101,'Nádražní'),null);
console.log('Facade review: geographic cardinal walls, road viewpoints, bearings, missing coverage and street queue OK');
