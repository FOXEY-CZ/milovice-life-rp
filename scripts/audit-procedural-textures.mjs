import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {writeFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
// Test the actual isolated staged modules, not a second implementation.
const [root,out]=process.argv.slice(2);
assert.ok(root&&out,'Usage: audit-procedural-textures.mjs <stage> <new-json>');
const load=path=>import(pathToFileURL(resolve(root,'scripts',path)).href);
const [{makeHZSShellPalette5315,makeHZSCladding5315},{makeJuventaFacade5307},{makeTopolovaZebraPaintPixels5187}]=await Promise.all([
 load('osm-hzs-facade-5315.js'),load('osm-juventa-school-facade-5307.js'),load('osm-topolova-zebra-paint-5187.js')
]);
const records=[];
function record(id,generate,width,height,validate){
 const a=generate(),b=generate();
 assert.ok(a&&b&&a.data instanceof Uint8Array,id+' missing generated bytes');
 assert.equal(a.width,width);assert.equal(a.height,height);
 assert.equal(a.data.byteLength,width*height*4);
 assert.deepEqual(a.data,b.data,id+' not deterministic');
 for(let i=3;i<a.data.length;i+=4)assert.equal(a.data[i],255,id+' alpha');
 validate(a);
 records.push({id,width,height,bytes:a.data.byteLength,sha256:createHash('sha256').update(a.data).digest('hex'),deterministic:true,review:'pending'});
}
const rgb=(data,i)=>Array.from(data.subarray(i*4,i*4+3));
record('fire-station-cladding',()=>makeHZSCladding5315(64),1,64,a=>{
 assert.equal(a.photoPixels,0);assert.deepEqual(rgb(a.data,0),[0x63,0x73,0x7a]);
 assert.deepEqual(rgb(a.data,1),[0xa9,0xb7,0xbc]);assert.deepEqual(rgb(a.data,2),[0x84,0x96,0x9d]);
 for(let i=8;i<64;i++)assert.deepEqual(rgb(a.data,i),rgb(a.data,i%8));
});
record('fire-station-shell',makeHZSShellPalette5315,1,128,a=>{
 assert.equal(a.photoPixels,0);assert.equal(a.plasterRows,64);
 for(let i=0;i<64;i++)assert.deepEqual(rgb(a.data,i),[0xe4,0xe2,0xdd]);
 assert.deepEqual(a.data.subarray(256),makeHZSCladding5315(64).data);
});
record('school-shell-height-15.25',()=>makeJuventaFacade5307(15.25),1,128,a=>{
 assert.equal(a.bandRows,8);
 for(let i=0;i<128;i++)assert.deepEqual(rgb(a.data,i),i<8?[0x54,0x4c,0x47]:[0xe4,0xd9,0xbe]);
});
record('zebra-paint',makeTopolovaZebraPaintPixels5187,64,64,a=>{
 assert.equal(a.visualVariationPhotoVerified,false);
 assert.equal(a.byteCount,16384);
 const colors=new Set();
 for(let i=0;i<a.data.length;i+=4){
  const [r,g,b]=a.data.subarray(i,i+3);
  assert.equal(r-g,12);assert.equal(g-b,23);
  assert.ok(r>=226&&r<=252);colors.add(r);
 }
 assert.ok(colors.size>1);
});
assert.equal(makeHZSCladding5315(7),null);
assert.equal(makeJuventaFacade5307(0),null);
assert.equal(makeTopolovaZebraPaintPixels5187(32),null);
writeFileSync(out,JSON.stringify({schema:1,review:'pending',scope:'four outputs from three manually inspected procedural generators',records},null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({generated:records.length,records}));
