import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {panoramaHouseFallback} from './stage-panorama-house-fallback.mjs';
import {parseApprovedArchitectureManifest} from './architecture-manifest.js';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const path='data/architecture/verified-buildings.json',id='202385910';
const original=read(path),before=JSON.parse(original),after=JSON.parse(panoramaHouseFallback(path,original));
assert.equal(Object.keys(before.buildings).length,5);
assert.equal(Object.keys(after.buildings).length,4);
assert.ok(!Object.hasOwn(after.buildings,id));
for(const [key,value] of Object.entries(after.buildings))assert.deepEqual(value,before.buildings[key]);
assert.equal(parseApprovedArchitectureManifest(after).size,4);
assert.equal(parseApprovedArchitectureManifest(before).size,5);
assert.throws(()=>panoramaHouseFallback(path,JSON.stringify(after)),/Unexpected Panorama card identity/);
const index=read('index.html'),changed=panoramaHouseFallback('index.html',index);
assert.ok(changed.includes('const isPionyru2022PhotoGable=false;'));
assert.ok(changed.includes("localArchitecture.delete('202385910')"));
assert.ok(changed.includes('const modelCard=isEditableHouse?architectureCards.cards.get(String(osmId))||null:null;'));
assert.ok(changed.includes('if(isPionyru2022PhotoGable){'));
assert.throws(()=>panoramaHouseFallback('index.html',changed),/marker changed/);
const mapPath='data/milovice-osm.json',raw=read(mapPath);
assert.equal(panoramaHouseFallback(mapPath,raw),raw);
const way=JSON.parse(raw).elements.find(e=>String(e.id)===id);
assert.equal(way.tags.building,'residential');
assert.equal(way.tags['building:levels'],'1');
assert.ok(way.geometry.length>=4);
assert.deepEqual(way.geometry[0],way.geometry.at(-1));
console.log('PASS candidate source transform: one card omitted, other four unchanged, OSM source untouched; no browser verification');
